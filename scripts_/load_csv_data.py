import pandas as pd
import numpy as np
from pathlib import Path



def parse_keyence_csv_file(file_name):
    '''
    function that reads a csv file generated by the Keyence software containing image height data
    
    Parameters:
        filename: str, the path to the csv file. Must end with '_Height.csv'

    Returns:
        data : ndarray, height data
        calibration: float, pixel size in µm
    '''

    file_name = Path(file_name)

    if not file_name.name.endswith("_Height.csv"):
        raise ValueError(f"Expected a file ending with '_Height.csv', got '{file_name.name}'")

    # read calibration from metadata
    with open(file_name, "r") as file:
        lines = file.readlines()

    calib_line = lines[10].strip().replace('"', '')
    parts = [p.strip() for p in calib_line.split(';')]

    try:
        calibration = float(parts[1].replace(',', ''))
    except (IndexError, ValueError):
        raise ValueError(f"Could not parse calibration line: {calib_line}")

    # load height data
    df = pd.read_csv(
        file_name,
        sep=';',
        skiprows=19,
        header=None,
        decimal=',',
    )

    data = df.astype(float).to_numpy()

    
    return data, calibration




def parse_created_csv_file(file_name):
    '''
    function that reads a csv file containing image height data generated by the 'vk_height_to_csv' function
    
    Parameters:
        filename: str, the path to the csv file. Must end with '_csv.csv'

    Returns:
        data : ndarray, height data
        calibration: float, pixel size in µm
    '''

    file_name = Path(file_name)

    if not file_name.name.endswith("_csv.csv"):
        raise ValueError(f"Expected a file ending with '_csv.csv', got '{file_name.name}'")

    # read calibration from metadata
    with open(file_name, "r") as file:
        lines = file.readlines()

    calibration = float(lines[4].split(':')[1])
    #calibration = float(lines[4].split(',')[1])
    

    # load height data
    df = pd.read_csv(
        file_name,
        sep=';',
        skiprows=19,
        header=None,
        decimal='.',
    )

    data = df.astype(float).to_numpy()

    
    return data, calibration