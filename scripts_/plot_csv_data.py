from scripts_.load_csv_data import parse_keyence_csv_file, parse_created_csv_file
from scripts_.plot_vk_data import plot_height_data




def plot_keyence_csv_height(file_name, colormap='viridis', scale='absolute'):
    '''
    Plot a single height csv file generated by the Keyence software.

    Parameters:
        filename : str, csv file ending in '_Height.csv'.

    Returns:
        ax : matplotlib.axes.Axes
    '''

    data, calibration = parse_keyence_csv_file(file_name)

    height_px, width_px = data.shape

    ax = plot_height_data(
        data,
        width_px,
        height_px,
        calibration=calibration,
        colormap=colormap,
        scale=scale
    )

    return ax



